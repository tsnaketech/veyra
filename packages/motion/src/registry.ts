import { z } from "zod";

/**
 * A motion component turns validated parameters into escaped HTML plus animation
 * *data* (tweens, counters). Only Veyra's fixed composer writes JavaScript: neither
 * a model nor a parameter can inject code.
 */
export const easeSchema = z.enum([
  "none",
  "power1.out",
  "power2.out",
  "power3.out",
  "sine.out",
  "sine.inOut",
  "back.out(1.4)",
]);
const n = (min: number, max: number) => z.number().min(min).max(max);
export const tweenVarsSchema = z
  .object({
    opacity: n(0, 1),
    x: n(-4000, 4000),
    y: n(-4000, 4000),
    xPercent: n(-200, 200),
    yPercent: n(-200, 200),
    scale: n(0, 4),
    scaleX: n(0, 4),
    scaleY: n(0, 4),
    rotation: n(-360, 360),
  })
  .partial()
  .strict();
// Selectors are generated by components, never by a model: ids and classes only.
const selector = z.string().regex(/^#scene-\d+(?: \.[a-z][a-z0-9-]*)*$/);
export const tweenSchema = z
  .object({
    target: selector,
    from: tweenVarsSchema,
    to: tweenVarsSchema,
    /** Seconds from the start of the scene. */
    at: n(0, 60),
    duration: n(0, 15),
    ease: easeSchema,
    stagger: n(0, 2).optional(),
    repeat: z.number().int().min(0).max(3).optional(),
    yoyo: z.boolean().optional(),
  })
  .strict();
export type Tween = z.infer<typeof tweenSchema>;
export const counterSchema = z
  .object({
    target: selector,
    from: n(0, 1e9),
    to: n(0, 1e9),
    decimals: z.number().int().min(0).max(2),
    prefix: z.string().max(4),
    suffix: z.string().max(6),
    at: n(0, 60),
    duration: n(0, 15),
  })
  .strict();
export type Counter = z.infer<typeof counterSchema>;

export const accentSchema = z.enum(["violet", "blue", "cyan"]);
/** Style options every component accepts. */
export const baseStyle = {
  accent: accentSchema.default("cyan"),
  align: z.enum(["center", "left"]).default("center"),
};
export const capabilitySchema = z.enum([
  "headline",
  "kinetic-text",
  "list",
  "stagger",
  "numbers",
  "counter",
  "product-ui",
  "chart",
  "device-frame",
  "call-to-action",
  "pulse",
]);
export type Capability = z.infer<typeof capabilitySchema>;

export interface BuildContext {
  /** DOM id of the scene wrapper, e.g. "scene-2"; every selector starts with it. */
  sceneId: string;
  durationS: number;
  /** Entrance pace in seconds (the scene's animation.durationMs). */
  entryS: number;
  width: number;
  height: number;
  palette: Record<z.infer<typeof accentSchema>, string>;
}
export interface BuiltScene {
  html: string;
  tweens: Tween[];
  counters: Counter[];
  events: VisualEvent[];
}
export interface MotionComponent<
  P extends z.ZodType = z.ZodType,
  S extends z.ZodType = z.ZodType,
> {
  id: string;
  version: 1;
  name: string;
  description: string;
  params: P;
  style: S;
  timing: { minMs: number; maxMs: number; defaultMs: number };
  capabilities: readonly Capability[];
  /** Text parameter that a "replace the text" correction edits; also the scene label. */
  primaryField: string;
  example: z.input<P>;
  build(params: z.infer<P>, style: z.infer<S>, ctx: BuildContext): BuiltScene;
}
export const defineComponent = <P extends z.ZodType, S extends z.ZodType>(
  component: MotionComponent<P, S>,
) => component;

export const escapeHtml = (value: string) =>
  value.replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ]!,
  );
/** JSON safe to embed in an inline <script>: no "</script>" or HTML comment can close it. */
export const scriptJson = (value: unknown) =>
  JSON.stringify(value)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
const numberFormats = new Map<number, Intl.NumberFormat>();
/** French number formatting, identical in Node (initial HTML) and Chrome (counter updates). */
export function formatCounter(
  value: number,
  counter: Pick<Counter, "decimals" | "prefix" | "suffix">,
) {
  let format = numberFormats.get(counter.decimals);
  if (!format) {
    format = new Intl.NumberFormat("fr-FR", {
      minimumFractionDigits: counter.decimals,
      maximumFractionDigits: counter.decimals,
    });
    numberFormats.set(counter.decimals, format);
  }
  return `${counter.prefix}${format.format(value)}${counter.suffix}`;
}

export const visualEventSchema = z
  .object({
    name: z.string().regex(/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/),
    atS: z.number().nonnegative(),
    endS: z.number().nonnegative(),
    index: z.number().int().nonnegative(),
  })
  .strict()
  .refine((e) => e.endS >= e.atS, "Invalid visual event interval");
export type VisualEvent = z.infer<typeof visualEventSchema>;
/** Derive timing from animation data, including stagger and repeated cycles. */
export function tweenEvent(
  name: string,
  tween: Tween,
  index = 0,
  count = 1,
): VisualEvent {
  const atS = tween.at + index * (tween.stagger ?? 0);
  return {
    name,
    index,
    atS,
    endS:
      atS +
      tween.duration * (1 + (tween.repeat ?? 0)) +
      (count - 1) * (tween.stagger ?? 0),
  };
}
